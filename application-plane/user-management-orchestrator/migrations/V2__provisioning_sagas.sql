-- =============================================================================
-- user-management-orchestrator (database medicitas_user_orchestrator, schema provisioning) — RF2
-- Persisted saga state for user provisioning against Keycloak (ADR-0012).
-- =============================================================================

CREATE TABLE saga_instances (
    id                uuid        PRIMARY KEY,
    tenant_id         uuid        NOT NULL,
    saga_type         text        NOT NULL,
    target_user_id    uuid        NOT NULL,
    status            text        NOT NULL DEFAULT 'started',
    request           jsonb       NOT NULL,
    result            jsonb,
    error_code        text,
    error_detail      text,
    actor_subject     uuid        NOT NULL,
    correlation_id    uuid        NOT NULL,
    deadline_at       timestamptz NOT NULL,
    version           integer     NOT NULL DEFAULT 1,
    created_at        timestamptz NOT NULL DEFAULT clock_timestamp(),
    updated_at        timestamptz NOT NULL DEFAULT clock_timestamp(),
    completed_at      timestamptz,
    CONSTRAINT saga_instances_tenant_id_unique UNIQUE (tenant_id, id),
    CONSTRAINT saga_instances_type CHECK (saga_type IN ('user-creation', 'user-role-change', 'user-deactivation')),
    CONSTRAINT saga_instances_status CHECK (status IN (
        'started', 'reserved', 'identity_provisioned', 'activating', 'completed', 'compensating', 'failed')),
    CONSTRAINT saga_instances_terminal_completed_at CHECK (
        (status IN ('completed', 'failed')) = (completed_at IS NOT NULL)),
    CONSTRAINT saga_instances_failed_has_error CHECK (status <> 'failed' OR error_code IS NOT NULL),
    CONSTRAINT saga_instances_request_has_no_password CHECK (request -> 'temporaryPassword' IS NULL)
);

COMMENT ON TABLE saga_instances IS 'User provisioning sagas (RF2): creation, role change, deactivation. Passwords are never stored.';
COMMENT ON COLUMN saga_instances.id IS 'Saga identifier; also the public operationId.';
COMMENT ON COLUMN saga_instances.target_user_id IS 'users.id in user-management targeted by the saga (generated by the orchestrator on creation).';
COMMENT ON COLUMN saga_instances.status IS 'started → reserved → identity_provisioned → activating → completed | compensating → failed (steps not used by a saga type are skipped).';
COMMENT ON COLUMN saga_instances.request IS 'Minimized request snapshot (no password).';
COMMENT ON COLUMN saga_instances.deadline_at IS 'After this instant the sweeper compensates a non-terminal saga.';

-- At most one running provisioning saga per target user (serializes role change vs deactivation).
CREATE UNIQUE INDEX saga_instances_one_open_per_user ON saga_instances (tenant_id, target_user_id)
    WHERE status NOT IN ('completed', 'failed');
COMMENT ON INDEX saga_instances_one_open_per_user IS 'Prevents concurrent sagas on the same user (409 OPERATION_IN_PROGRESS).';

CREATE INDEX saga_instances_open_deadline_idx ON saga_instances (deadline_at)
    WHERE status NOT IN ('completed', 'failed');
COMMENT ON INDEX saga_instances_open_deadline_idx IS 'Sweeper: non-terminal sagas by deadline.';

CREATE TABLE saga_steps (
    tenant_id          uuid        NOT NULL,
    saga_id            uuid        NOT NULL,
    step_name          text        NOT NULL,
    status             text        NOT NULL DEFAULT 'pending',
    command_message_id uuid,
    attempts           integer     NOT NULL DEFAULT 0,
    last_attempt_at    timestamptz,
    next_attempt_at    timestamptz,
    result             jsonb,
    error_code         text,
    created_at         timestamptz NOT NULL DEFAULT clock_timestamp(),
    updated_at         timestamptz NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT saga_steps_pk PRIMARY KEY (saga_id, step_name),
    CONSTRAINT saga_steps_saga_fk FOREIGN KEY (tenant_id, saga_id) REFERENCES saga_instances (tenant_id, id),
    CONSTRAINT saga_steps_name CHECK (step_name IN (
        'reserve_user', 'keycloak_user', 'keycloak_role', 'keycloak_disable', 'activate_user',
        'change_role', 'deactivate_user', 'cancel_reservation', 'restore_keycloak_role', 'delete_keycloak_user')),
    CONSTRAINT saga_steps_status CHECK (status IN (
        'pending', 'dispatched', 'succeeded', 'rejected', 'failed', 'compensating', 'compensated', 'skipped')),
    CONSTRAINT saga_steps_attempts_non_negative CHECK (attempts >= 0)
);

COMMENT ON TABLE saga_steps IS 'One row per saga step: dispatch, retries and persisted reply or Keycloak result.';
COMMENT ON COLUMN saga_steps.command_message_id IS 'messageId of the command (re-sent with the same id for idempotency).';
COMMENT ON COLUMN saga_steps.result IS 'Reply result or Keycloak artifact ids with createdBySaga flags.';

CREATE TRIGGER saga_instances_touch_updated_at BEFORE UPDATE ON saga_instances
    FOR EACH ROW EXECUTE FUNCTION app.touch_updated_at();
CREATE TRIGGER saga_steps_touch_updated_at BEFORE UPDATE ON saga_steps
    FOR EACH ROW EXECUTE FUNCTION app.touch_updated_at();

ALTER TABLE saga_instances ENABLE ROW LEVEL SECURITY;
ALTER TABLE saga_instances FORCE ROW LEVEL SECURITY;
ALTER TABLE saga_steps ENABLE ROW LEVEL SECURITY;
ALTER TABLE saga_steps FORCE ROW LEVEL SECURITY;

CREATE POLICY tenant_isolation ON saga_instances
    USING (tenant_id = app.current_tenant_id()) WITH CHECK (tenant_id = app.current_tenant_id());
CREATE POLICY tenant_isolation ON saga_steps
    USING (tenant_id = app.current_tenant_id()) WITH CHECK (tenant_id = app.current_tenant_id());
CREATE POLICY worker_discovery ON saga_instances FOR SELECT TO ${rolePrefix}_worker USING (true);
CREATE POLICY worker_discovery ON saga_steps FOR SELECT TO ${rolePrefix}_worker USING (true);

