import { newId } from '@medicitas/kernel';
import type { EventSink } from '@medicitas/messaging';
import {
  activateUser,
  cancelReservation,
  changeRole,
  deactivateUser,
  type ClinicRole,
  type User,
} from '../../domain/entities/user.js';
import { userNotFound } from '../../domain/errors/user-errors.js';
import {
  USER_EVENTS,
  userActivatedPayload,
  userDeactivatedPayload,
  userRoleChangedPayload,
} from '../../domain/events/user-events.js';
import type { TenantReplicaRepository, UserRepository } from '../ports/repositories.js';

export interface ReserveUserInput {
  readonly tenantId: string;
  readonly userId: string;
  readonly email: string;
  readonly firstName: string;
  readonly lastName: string;
  readonly role: ClinicRole;
  readonly sagaId: string | null;
}

/**
 * ReserveUserCommand (RF2 step 2): inserts a `provisioning` row. Idempotent by the natural key
 * userId (generated by the orchestrator); e-mail uniqueness is realm-wide (EMAIL_TAKEN).
 */
export async function reserveUser(users: UserRepository, input: ReserveUserInput): Promise<User> {
  const existing = await users.findById(input.userId);
  if (existing !== null) return existing;
  return users.insert({
    id: input.userId,
    tenantId: input.tenantId,
    email: input.email.toLowerCase(),
    firstName: input.firstName.trim(),
    lastName: input.lastName.trim(),
    role: input.role,
    keycloakSubject: null,
    status: 'provisioning',
    provisioningSagaId: input.sagaId,
  });
}

async function load(users: UserRepository, userId: string): Promise<User> {
  const user = await users.findById(userId, { forUpdate: true });
  if (user === null) throw userNotFound();
  return user;
}

export async function activateReservedUser(
  users: UserRepository,
  events: EventSink,
  input: { readonly userId: string; readonly keycloakSubject: string },
): Promise<User> {
  const transition = activateUser(await load(users, input.userId), input.keycloakSubject);
  if (!transition.changed) return transition.user;
  const saved = await users.save(transition.user);
  await events.emit({ ...USER_EVENTS.userActivated, payload: userActivatedPayload(saved) });
  return saved;
}

export async function cancelUserReservation(users: UserRepository, input: { readonly userId: string }): Promise<User> {
  const transition = cancelReservation(await load(users, input.userId));
  return transition.changed ? users.save(transition.user) : transition.user;
}

export async function changeUserRole(
  users: UserRepository,
  events: EventSink,
  input: { readonly userId: string; readonly role: ClinicRole },
): Promise<User> {
  const current = await load(users, input.userId);
  const transition = changeRole(current, input.role);
  if (!transition.changed) return transition.user;
  const saved = await users.save(transition.user);
  await events.emit({ ...USER_EVENTS.userRoleChanged, payload: userRoleChangedPayload(saved, current.role) });
  return saved;
}

export async function deactivateTenantUser(
  users: UserRepository,
  events: EventSink,
  input: { readonly userId: string; readonly actorSubject: string | null },
  now: Date = new Date(),
): Promise<User> {
  const transition = deactivateUser(await load(users, input.userId), input.actorSubject, now);
  if (!transition.changed) return transition.user;
  const saved = await users.save(transition.user);
  await events.emit({ ...USER_EVENTS.userDeactivated, payload: userDeactivatedPayload(saved) });
  return saved;
}

export interface TenantOnboardedInput {
  readonly tenantId: string;
  readonly slug: string;
  readonly name: string;
  readonly timezone: string;
  readonly aggregateVersion: number;
  readonly firstAdmin: { readonly subject: string; readonly email: string; readonly firstName: string; readonly lastName: string };
}

/**
 * TenantOnboarded (RF1 consequence): replicates the tenant and registers its first clinic admin,
 * already active (the onboarding saga created the Keycloak identity).
 */
export async function applyTenantOnboarded(
  tenants: TenantReplicaRepository,
  users: UserRepository,
  input: TenantOnboardedInput,
): Promise<void> {
  await tenants.upsert({
    id: input.tenantId,
    slug: input.slug,
    name: input.name,
    timezone: input.timezone,
    status: 'active',
    version: input.aggregateVersion,
  });
  if ((await users.findBySubject(input.firstAdmin.subject)) !== null) return;
  await users.insert({
    id: newId(),
    tenantId: input.tenantId,
    email: input.firstAdmin.email.toLowerCase(),
    firstName: input.firstAdmin.firstName,
    lastName: input.firstAdmin.lastName,
    role: 'clinic_admin',
    keycloakSubject: input.firstAdmin.subject,
    status: 'active',
    provisioningSagaId: null,
  });
}
